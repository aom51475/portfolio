export function readArts() {
  return [...document.querySelectorAll('#plain figure[data-art]')].map((fig, index) => {
    const id = fig.dataset.art, img = fig.querySelector('img');
    return {
      id, index, fig,
      kind: fig.dataset.kind || '',
      ar: parseFloat(fig.dataset.ar) || 1.3333,
      title: fig.querySelector('figcaption b')?.textContent.trim() || '',
      text: fig.querySelector('figcaption span')?.textContent.trim() || '',
      alt: img?.alt || '',
      full: `img/full/${id}.jpg`,
      tex: `img/tex/${id}.webp`,
    };
  });
}

